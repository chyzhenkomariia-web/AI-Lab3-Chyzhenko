"""Завдання 2. Zero-shot і few-shot prompting.

Задача: визначити тип машинного навчання для опису задачі.
Кожен тестовий випадок надсилається двічі: без прикладів і з трьома прикладами.
"""
from llm_client import send_prompt

TASK = "task2"

test_cases = [
    "Програма вчиться грати в шахи, отримуючи бали за перемоги та штрафи за поразки.",
    "Поштовий сервіс навчається відрізняти спам від звичайних листів на основі "
    "тисяч листів, які користувачі вже позначили як спам.",
    "Новинний сайт автоматично групує статті за схожими темами, хоча заздалегідь "
    "теми ніхто не визначав.",
]

ZERO_SHOT = "Визнач, до якого типу машинного навчання належить задача: {case}"

FEW_SHOT = """Визнач тип машинного навчання для задачі. Відповідай строго у форматі прикладів.

Задача: Прогнозування ціни квартири за площею та районом на основі історичних продажів.
Тип: Навчання з учителем
Причина: є розмічені дані — відомі ціни проданих квартир.

Задача: Поділ клієнтів інтернет-магазину на групи за їхньою поведінкою.
Тип: Навчання без учителя
Причина: групи заздалегідь невідомі, модель сама шукає схожість.

Задача: Робот вчиться ходити, отримуючи винагороду за кожен крок без падіння.
Тип: Навчання з підкріпленням
Причина: агент навчається через винагороди та покарання за свої дії.

Задача: {case}
Тип:"""

for number, case in enumerate(test_cases, 1):
    send_prompt(TASK, f"Zero-shot, випадок {number}", ZERO_SHOT.format(case=case))
    send_prompt(TASK, f"Few-shot, випадок {number}", FEW_SHOT.format(case=case))
