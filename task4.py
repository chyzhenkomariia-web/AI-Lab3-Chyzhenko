"""Завдання 4. Системна роль.

Запит однаковий для всіх ролей, змінюється лише системна інструкція
(параметр system_instruction у Gemini API).
"""
from llm_client import send_prompt

TASK = "task4"

question = "Поясни, що таке рекурсія."

roles = {
    "Викладач": "Ти — викладач, який пояснює матеріал студентам-початківцям. "
                "Пояснюєш поступово, з аналогіями з повсякденного життя.",
    "Програміст": "Ти — досвідчений програміст. Пояснюєш практично: з кодом, "
                  "типовими помилками та порадами для реальних проєктів.",
    "Науковець": "Ти — науковець у галузі теоретичної інформатики. Використовуєш "
                 "точну термінологію, формальні визначення та посилаєшся на теорію.",
}

for role, instruction in roles.items():
    send_prompt(TASK, f"Роль: {role}", question, system=instruction)
