"""Завдання 3. Удосконалення prompt: розмитий запит проти конкретного."""
from llm_client import send_prompt

TASK = "task3"

initial = "Розкажи про штучний інтелект."

improved = """Ти — викладач інформатики.

Поясни студентам першого курсу, які ще не вивчали програмування, що таке штучний інтелект.

Розкажи:
1) що це таке (одним реченням);
2) чим ШІ відрізняється від звичайної програми;
3) три приклади ШІ, з якими студенти стикаються щодня.

Обсяг — до 150 слів. Формат: короткий вступ і нумерований список.
Пиши простою мовою, без термінів або з їх поясненням."""

send_prompt(TASK, "Початковий prompt", initial)
send_prompt(TASK, "Вдосконалений prompt", improved)
