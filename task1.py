"""Завдання 1. П'ять типів запитів до LLM (предметна область — штучний інтелект)."""
from llm_client import send_prompt

TASK = "task1"

send_prompt(TASK, "1. Пояснення",
            "Поясни простими словами, що таке нейронна мережа.")

send_prompt(TASK, "2. Генерація тексту",
            "Напиши короткий текст (5–6 речень) на тему "
            "«Роль штучного інтелекту в сучасній освіті».",
            temperature=0.7)  # творче завдання, тому вища temperature

english = ("Machine learning is a branch of artificial intelligence that allows "
           "computers to learn from data without being explicitly programmed. "
           "Instead of following fixed rules, a machine learning model finds "
           "patterns in examples and uses them to make predictions about new data.")
send_prompt(TASK, "3. Переклад",
            f"Переклади українською мовою:\n\n{english}")

llm_text = (
    "Великі мовні моделі (LLM) — це нейронні мережі, навчені на величезних обсягах "
    "текстових даних з інтернету, книжок і статей. Вони працюють на основі "
    "архітектури трансформер, яка дозволяє враховувати контекст усього речення чи "
    "навіть цілого документа. Під час навчання модель вчиться передбачати наступне "
    "слово в тексті, і завдяки цьому набуває здатності відповідати на запитання, "
    "перекладати, писати код і створювати тексти. Сьогодні LLM використовуються в "
    "чат-ботах, пошукових системах, офісних програмах та інструментах для "
    "програмістів. Проте такі моделі можуть помилятися або вигадувати факти, тому "
    "їхні відповіді варто перевіряти."
)
send_prompt(TASK, "4. Узагальнення",
            f"Скороти та узагальни цей текст до 2 речень:\n\n{llm_text}")

send_prompt(TASK, "5. Генерація списку",
            "Склади список із 5 мов програмування, які найчастіше використовують "
            "для розробки систем штучного інтелекту. Для кожної вкажи одну головну перевагу.")
